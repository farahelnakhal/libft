#include "libft.h"

char	*ft_strchr(const char *s, int c)
{
	c = (char) c;
	while (*s)
	{
		if (*s == c)
			return ((char *) s);
		s++;
	}
	if (c == '\0')
		return ((char *) s);
	return (NULL);
}
